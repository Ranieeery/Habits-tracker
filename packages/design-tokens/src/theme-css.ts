import {
	colors,
	fontFamily,
	nightColors,
	nightFonts,
	radius,
	spacing,
} from "./tokens.ts";

type ColorTree = { readonly [key: string]: string | ColorTree };

function flattenColors(tree: ColorTree, prefix: string): [string, string][] {
	return Object.entries(tree).flatMap(([key, value]) => {
		const name = key === "DEFAULT" ? prefix : `${prefix}-${key}`;
		return typeof value === "string"
			? [[name, value] as [string, string]]
			: flattenColors(value, name);
	});
}

function fontStack(fonts: readonly string[]): string {
	return fonts
		.map((font) =>
			font.includes("-") && !font.includes(" ") ? font : `"${font}"`
		)
		.join(", ");
}

/**
 * One declaration inside `@theme`, broken after the colon when it would pass
 * 80 columns (a tab counts as 2), as Prettier formats it, so the committed
 * file passes `format:check`.
 */
function indent(line: string): string {
	if (line.length + 2 <= 80) return `\t${line}`;
	const colon = line.indexOf(": ");
	return `\t${line.slice(0, colon + 1)}\n\t\t${line.slice(colon + 2)}`;
}

/**
 * Renders the tokens as a Tailwind v4 `@theme` block (web): the same tokens
 * as the mobile preset (`night` set and the deprecated aliases).
 */
export function renderThemeCss(): string {
	const lines = [
		...flattenColors(colors, "--color").map(
			([name, value]) => `${name}: ${value};`
		),
		...Object.entries(radius).map(
			([name, value]) => `--radius-${name}: ${value};`
		),
		...Object.entries(spacing).map(
			([name, value]) => `--spacing-${name}: ${value};`
		),
		`--font-sans: ${fontStack(fontFamily.sans)};`,
		...flattenColors(nightColors, "--color-night").map(
			([name, value]) => `${name}: ${value};`
		),
		`--font-display: ${fontStack(nightFonts.display)};`,
	];

	return [
		"/* Generated by packages/design-tokens (pnpm --filter @habits/design-tokens generate). Do not edit. */",
		"@theme {",
		...lines.map(indent),
		"}",
		"",
	].join("\n");
}
